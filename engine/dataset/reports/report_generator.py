import os
from typing import Any, Dict, Optional


class DatasetReportGenerator:
    """Generates markdown profiles detailing quality, vocabulary stats, and cleaning pipelines."""

    @staticmethod
    def generate_report(
        stats: Dict[str, Any], output_path: str, cleaning_info: Optional[Dict[str, Any]] = None
    ) -> str:
        cleaning_info = cleaning_info or {}
        lang_data = stats.get("languages", {"en": 1})
        primary_lang = max(lang_data.keys(), key=lambda k: lang_data[k]) if lang_data else "unknown"

        char_stats = stats.get("char_stats", {})
        token_stats = stats.get("token_stats", {})
        vocab_stats = stats.get("vocabulary", {})
        special_stats = stats.get("special_tokens", {})

        report_content = f"""# Chatii Dataset Profile & Quality Report

## Executive Summary
- **Total Samples**: {stats.get("sample_count", 0):,}
- **Total Tokens**: {stats.get("token_count", 0):,}
- **Primary Language**: `{primary_lang}`
- **Average Character Length**: {char_stats.get("average", 0.0):.2f} chars
- **Average Token Length**: {token_stats.get("average", 0.0):.2f} tokens

## Vocabulary & Coverage
- **Unique Tokens Seen**: {vocab_stats.get("unique_tokens_seen", 0):,}
- **Vocabulary Coverage**: {vocab_stats.get("coverage_pct", 0.0):.2f}%
- **OOV / Unknown Token Ratio**: {vocab_stats.get("oov_ratio_pct", 0.0):.4f}%

## Token Distributions
- **EOS Token Frequency**: {special_stats.get("eos_frequency", 0):,}
- **PAD Token Frequency**: {special_stats.get("pad_frequency", 0):,}
- **Padding wasted ratio**: {stats.get("padding_pct", 0.0):.2f}%

## Cleaning & Filtering Actions
- **Unicode Normalized**: {cleaning_info.get("normalize_unicode", "Yes")}
- **HTML Tags Stripped**: {cleaning_info.get("clean_html", "Yes")}
- **Whitespace Consolidated**: {cleaning_info.get("trim_whitespace", "Yes")}
- **Duplicates Removed**: {cleaning_info.get("duplicates_removed", 0):,} ({cleaning_info.get("duplicate_pct", 0.0):.2f}%)
- **Toxicity Flagged / Redacted**: {cleaning_info.get("profanity_flagged", 0):,}

---
*Report automatically generated by Chatii Dataset Engine.*
"""
        os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(report_content)

        return report_content
